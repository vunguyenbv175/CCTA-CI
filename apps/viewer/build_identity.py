"""Governed implementation identity for the viewer (r2 F11 prescription).

The viewer mints provenance whose ``Environment.code_commit_sha`` must be the
REAL identity of the code checkout the engine runs from — never forty zeros,
never a caller-supplied constant, never an environment-variable override, and
never a typed UNKNOWN (that would widen the shared provenance schema; r2 Axis
C rejected it explicitly).

Mechanism (prescribed verbatim by ``reports/VIEWER_001_REVIEW_R2.md``, F11):
resolve the repository root from THIS module's ``__file__`` (never from the
process CWD or request/session data), execute stdlib
``git -C <root> rev-parse --verify HEAD^{commit}``, require an exact
lowercase 40-hex commit that is not forty zeros, verify the checkout is a
git toplevel and the process runs from inside it, and verify the tracked
source bytes match that commit (index and working-tree diffs, plus untracked
executable source under the runtime package roots; report-only artifacts are
excluded).  Any unresolvable/dirty state fails closed with
:class:`BuildIdentityError`; the engine translates that into the existing
``ViewerOpenError(SESSION_OPEN_FAILED, ...)`` before any open state is
materialized.

Packaged/no-git distribution is NOT introduced here: governed operation
requires immutable, verifiable source for the engine's lifetime.
"""

from __future__ import annotations

import hashlib
import importlib.util
import os
import subprocess
from pathlib import Path
from typing import Final

_SHA_LENGTH: Final[int] = 40
_ZERO_SHA: Final[str] = "0" * _SHA_LENGTH
_HEX_DIGITS: Final[frozenset[str]] = frozenset("0123456789abcdef")
#: Report-only artifacts are excluded from the cleanliness gate (r2 F11.1).
_REPORT_ONLY_PREFIXES: Final[tuple[str, ...]] = ("reports/",)
#: Untracked *executable source* under these runtime package roots fails the
#: cleanliness gate; untracked non-source artifacts elsewhere do not.
_RUNTIME_PACKAGE_ROOTS: Final[tuple[str, ...]] = (
    "apps/",
    "core/",
    "models/",
    "validation/",
    "visualization/",
    "tests/",
)
_GIT_TIMEOUT_SECONDS: Final[int] = 60
_GIT_SANITIZED_PREFIXES: Final[tuple[str, ...]] = (
    "GIT_CONFIG",
    "GIT_DIR",
    "GIT_WORK_TREE",
    "GIT_INDEX_FILE",
    "GIT_OBJECT_DIRECTORY",
    "GIT_ALTERNATE_OBJECT_DIRECTORIES",
    "GIT_CEILING_DIRECTORIES",
)
#: Explicit non-source tool cache directory names (r4 R4-02 / r5 R5-02).
_CACHE_DIR_NAMES: Final[frozenset[str]] = frozenset({
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
})
#: Designated non-executable tool cache directory names (r5 R5-02).
_TOOL_CACHE_DIR_NAMES: Final[frozenset[str]] = frozenset({
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
})
#: Permitted Python interpreter bytecode extensions (r5 R5-02).
#: Note: .pyd is a native extension, not generated bytecode, and must never be exempted.
_BYTECODE_EXTENSIONS: Final[frozenset[str]] = frozenset({
    ".pyc",
    ".pyo",
})
#: Native extension extensions that must NEVER be excluded as cache (r5 R5-02).
_NATIVE_EXTENSION_EXTENSIONS: Final[frozenset[str]] = frozenset({
    ".so",
    ".dylib",
    ".pyd",
    ".dll",
})
#: Executable script and binary extensions that must NEVER be excluded (r5 R5-02).
_EXECUTABLE_EXTENSIONS: Final[frozenset[str]] = frozenset({
    ".sh",
    ".bash",
    ".exe",
    ".bin",
    ".cmd",
    ".bat",
})
#: Executable Python source extensions that must NEVER be excluded (r4 R4-02 / r5 R5-02).
_PYTHON_SOURCE_EXTENSIONS: Final[frozenset[str]] = frozenset({
    ".py",
    ".pyw",
    ".pyi",
})
#: Allowed non-executable extensions inside designated tool cache directories (r5 R5-02).
_ALLOWED_TOOL_CACHE_EXTENSIONS: Final[frozenset[str]] = frozenset({
    "",
    ".tag",
    ".md",
    ".json",
    ".txt",
    ".lock",
    ".db",
})


class BuildIdentityError(ValueError):
    """A fail-closed build-identity resolution or validation failure."""


def repo_root_from_file() -> Path:
    """The repository root, resolved from THIS module's location."""

    return Path(__file__).resolve().parents[2]


def _sanitized_git_env() -> dict[str, str]:
    """Sanitize ambient Git environment variables (r3 R3-02)."""

    return {
        k: v
        for k, v in os.environ.items()
        if not any(k.startswith(prefix) for prefix in _GIT_SANITIZED_PREFIXES)
    }


def _run_git(root: Path, *arguments: str) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            ["git", "-C", str(root), *arguments],
            check=False,
            capture_output=True,
            text=True,
            timeout=_GIT_TIMEOUT_SECONDS,
            env=_sanitized_git_env(),
        )
    except FileNotFoundError:
        raise BuildIdentityError("git executable not found on PATH") from None
    except subprocess.TimeoutExpired as exc:
        raise BuildIdentityError(f"git {arguments[0]!r} timed out") from exc


def validate_commit_sha(sha: object) -> str:
    """Require an exact lowercase 40-hex commit identity, never forty zeros."""

    if not isinstance(sha, str):
        raise BuildIdentityError(
            f"commit identity must be a string, got {type(sha).__name__}"
        )
    if len(sha) != _SHA_LENGTH or not set(sha) <= _HEX_DIGITS:
        raise BuildIdentityError(
            "commit identity must be an exact lowercase 40-hex string, "
            f"got {sha!r}"
        )
    if sha == _ZERO_SHA:
        raise BuildIdentityError(
            "governed implementation identity must never be forty zeros"
        )
    return sha


def _commit_exists(root: Path, sha: str) -> bool:
    result = _run_git(root, "rev-parse", "--verify", "--quiet", f"{sha}^{{commit}}")
    return result.returncode == 0 and result.stdout.strip() == sha


def verify_commit_exists(sha: str, repo_root: Path | str | None = None) -> str:
    """Require *sha* to be an existing governed commit in the checkout.

    Used for persisted viewer provenance: a historical producing SHA must
    refer to an actual governed commit (it is never required to equal a later
    replay runtime's HEAD).
    """

    resolved_root = repo_root_from_file()
    if repo_root is not None and Path(repo_root).resolve() != resolved_root:
        raise BuildIdentityError(
            f"supplied repo_root {repo_root} does not match the executing "
            f"code root {resolved_root}"
        )
    root = resolved_root
    validate_commit_sha(sha)
    if not _commit_exists(root, sha):
        raise BuildIdentityError(
            f"commit identity {sha} does not exist in the repository at {root}"
        )
    return sha


def _is_report_only(path: str) -> bool:
    return any(path.startswith(prefix) for prefix in _REPORT_ONLY_PREFIXES)


def _is_runtime_source(path: str) -> bool:
    return any(path.startswith(prefix) for prefix in _RUNTIME_PACKAGE_ROOTS)


def _is_allowed_cache_artifact(
    path: str | Path,
    root: Path | None = None,
    tracked_files: frozenset[str] | set[str] | None = None,
) -> bool:
    """Return True if path is a narrow, file-only generated cache artifact (r5 R5-01, R5-02).

    Never allows directory-summary entries under any circumstances (R5-01).
    Never allows sourceless bytecode, native extensions (.so, .dylib, .pyd, .dll),
    executable scripts, or arbitrary Python source anywhere (R5-02).
    Ordinary interpreter cache files (.pyc, .pyo) are permitted ONLY in their conventional
    cache location (__pycache__/) with an identifiable corresponding tracked source in git.
    Tool cache artifacts are permitted ONLY in designated tool cache directories
    (.pytest_cache, .mypy_cache, .ruff_cache) with allowed non-executable extensions.
    """

    if root is None:
        root = repo_root_from_file()

    p = Path(path)
    path_str = p.as_posix()

    # Refuse directory summaries early (R5-01)
    if path_str.endswith("/") or (root / p).is_dir():
        return False

    # Never exempt Python source, native extensions, or executable scripts anywhere (R5-02)
    if (
        p.suffix in _PYTHON_SOURCE_EXTENSIONS
        or p.suffix in _NATIVE_EXTENSION_EXTENSIONS
        or p.suffix in _EXECUTABLE_EXTENSIONS
    ):
        return False

    # Check executable bit on filesystem if file exists
    full_path = root / p
    if full_path.is_file() and os.access(full_path, os.X_OK):
        return False

    # Case A: Interpreter cache artifact in conventional __pycache__/ location (R5-02)
    if p.parent.name == "__pycache__":
        if p.suffix not in _BYTECODE_EXTENSIONS:
            return False

        if tracked_files is None:
            res = _run_git(root, "ls-files", "-z")
            if res.returncode == 0:
                tracked_files = frozenset(e for e in res.stdout.split("\0") if e)
            else:
                tracked_files = frozenset()

        candidate_sources: list[str] = []
        try:
            candidate_sources.append(
                Path(importlib.util.source_from_cache(path_str)).as_posix()
            )
        except (ValueError, AttributeError):
            pass

        # Fallback candidate for non-PEP 3147 naming
        module_stem = p.name.split(".")[0]
        grandparent = p.parent.parent
        for ext in (".py", ".pyw"):
            cand = (grandparent / f"{module_stem}{ext}").as_posix()
            if cand not in candidate_sources:
                candidate_sources.append(cand)

        return any(cand in tracked_files for cand in candidate_sources)

    # Case B: Tool cache artifact in designated tool cache directory (R5-02)
    if "__pycache__" not in p.parts:
        if any(tool_dir in p.parts for tool_dir in _TOOL_CACHE_DIR_NAMES):
            return p.suffix.lower() in _ALLOWED_TOOL_CACHE_EXTENSIONS

    return False


def verify_source_cleanliness(root: Path | None = None) -> None:
    """Verify tracked source bytes match HEAD (r2 F11.1 / r3 R3-02 / r4 R4-02, fail-closed).

    Independent of suppressible git status, ambient configuration, repository/user
    ignore sources (.git/info/exclude, .gitignore), and index optimization flags
    (assume-unchanged and skip-worktree).  Tracked runtime files are verified by direct
    committed-blob comparison; index flags are explicitly validated; untracked source
    is enumerated with pinned ``--untracked-files=all`` and a separate NUL-delimited
    ignore-independent enumeration ``git ls-files --others -z``.  Generated Python and
    tool cache artifacts are handled through narrow, explicit non-source exclusions
    in code.  Report-only artifacts remain excluded.
    """

    resolved_root = repo_root_from_file()
    if root is not None and Path(root).resolve() != resolved_root:
        raise BuildIdentityError(
            f"supplied root {root} does not match the executing code root {resolved_root}"
        )
    root = resolved_root

    # 1. Reject assume-unchanged and skip-worktree states (r3 R3-02)
    ls_files = _run_git(root, "ls-files", "-v", "-z")
    if ls_files.returncode != 0:
        raise BuildIdentityError("git ls-files failed: " + ls_files.stderr.strip())
    tracked_files_set: set[str] = set()
    for entry in ls_files.stdout.split("\0"):
        if not entry:
            continue
        tag = entry[0]
        path = entry[2:]
        if _is_report_only(path):
            continue
        if tag != "H":
            raise BuildIdentityError(
                f"dirty source: unsupported git index flag {tag!r} "
                f"(assume-unchanged or skip-worktree) on tracked path: {path}"
            )
        tracked_files_set.add(path)
    tracked_files: Final[frozenset[str]] = frozenset(tracked_files_set)

    # 2. Pinned git status covering index/worktree diffs and untracked files
    result = _run_git(
        root,
        "-c",
        "status.showUntrackedFiles=all",
        "status",
        "--porcelain",
        "-z",
        "--untracked-files=all",
    )
    if result.returncode != 0:
        raise BuildIdentityError("git status failed: " + result.stderr.strip())
    fields = result.stdout.split("\0")
    index = 0
    while index < len(fields):
        entry = fields[index]
        index += 1
        if not entry:
            continue
        status = entry[:2]
        path = entry[3:]
        if status[0] in {"R", "C"} and index < len(fields):
            index += 1  # rename/copy entries carry the original path next
        if _is_report_only(path):
            continue
        if status == "??":
            if _is_runtime_source(path):
                if path.endswith("/") or (root / path).is_dir():
                    raise BuildIdentityError(
                        "dirty source: untracked directory summary under a "
                        f"runtime package root: {path}"
                    )
                if not _is_allowed_cache_artifact(
                    path, root=root, tracked_files=tracked_files
                ):
                    raise BuildIdentityError(
                        "dirty source: untracked executable source under a "
                        f"runtime package root: {path}"
                    )
            continue
        raise BuildIdentityError(
            f"dirty source: tracked source does not match HEAD: {path} "
            f"(status={status!r})"
        )

    # 3. Direct committed blob comparison for tracked runtime source (r3 R3-02)
    tree = _run_git(root, "ls-tree", "-r", "-z", "HEAD", *_RUNTIME_PACKAGE_ROOTS)
    if tree.returncode != 0:
        raise BuildIdentityError("git ls-tree failed: " + tree.stderr.strip())
    for entry_str in tree.stdout.split("\0"):
        if not entry_str:
            continue
        meta, sep, path = entry_str.partition("\t")
        if not sep or _is_report_only(path):
            continue
        parts = meta.split()
        if len(parts) < 3 or parts[1] != "blob":
            continue
        committed_sha = parts[2]
        file_path = root / path
        if not file_path.is_file():
            raise BuildIdentityError(
                f"dirty source: tracked runtime file missing on disk: {path}"
            )
        try:
            data = file_path.read_bytes()
        except OSError as exc:
            raise BuildIdentityError(
                f"dirty source: cannot read tracked runtime file {path}: {exc}"
            ) from exc
        actual_sha = hashlib.sha1(
            b"blob " + str(len(data)).encode() + b"\0" + data
        ).hexdigest()
        if actual_sha != committed_sha:
            raise BuildIdentityError(
                f"dirty source: tracked source bytes do not match committed blob: {path}"
            )

    # 4. Ignore-independent enumeration of untracked paths (r4 R4-02 / r5 R5-01 / r5 R5-02)
    others = _run_git(
        root,
        "ls-files",
        "--others",
        "-z",
        "--",
        *_RUNTIME_PACKAGE_ROOTS,
    )
    if others.returncode != 0:
        raise BuildIdentityError(
            "git ls-files --others failed: " + others.stderr.strip()
        )
    for entry in others.stdout.split("\0"):
        if not entry:
            continue
        if _is_report_only(entry):
            continue
        if not _is_runtime_source(entry):
            continue
        if entry.endswith("/") or (root / entry).is_dir():
            raise BuildIdentityError(
                "dirty source: untracked directory summary under a "
                f"runtime package root: {entry}"
            )
        if _is_allowed_cache_artifact(
            entry, root=root, tracked_files=tracked_files
        ):
            continue
        raise BuildIdentityError(
            "dirty source: untracked executable source under a "
            f"runtime package root: {entry}"
        )


def resolve_build_identity(repo_root: Path | str | None = None) -> str:
    """Resolve and verify the immutable build identity of the code checkout.

    Fails closed on: an alternate supplied repo_root unequal to the executing
    code root, a process CWD outside the checkout (wrong CWD), a resolved root
    that is not its own git toplevel (nested-checkout identity theft), missing
    git, a missing/nonexistent HEAD identity, a malformed or all-zero identity,
    and any dirty tracked source or untracked runtime source. The identity is
    resolved from the checkout, never from the process CWD, request/session
    data, or an environment variable.
    """

    resolved_root = repo_root_from_file()
    if repo_root is not None and Path(repo_root).resolve() != resolved_root:
        raise BuildIdentityError(
            f"supplied repo_root {repo_root} does not match the executing "
            f"code root {resolved_root}"
        )
    root = resolved_root

    cwd = Path.cwd().resolve()
    if cwd != root and root not in cwd.parents:
        raise BuildIdentityError(
            f"wrong CWD: the process runs from {cwd}, outside the code "
            f"checkout {root}; governed identity resolution is refused"
        )

    head = _run_git(root, "rev-parse", "--verify", "HEAD^{commit}")
    if head.returncode != 0:
        raise BuildIdentityError(
            "git could not verify a HEAD commit identity: "
            + (head.stderr.strip() or f"exit code {head.returncode}")
        )
    sha = validate_commit_sha(head.stdout.strip())

    toplevel = _run_git(root, "rev-parse", "--show-toplevel")
    if toplevel.returncode != 0 or toplevel.stdout.strip() != str(root):
        raise BuildIdentityError(
            f"wrong CWD: {root} is not its own git toplevel "
            f"(toplevel={toplevel.stdout.strip() or 'unresolvable'}); the "
            "resolved identity could belong to an enclosing repository"
        )

    verify_source_cleanliness(root)
    return sha


